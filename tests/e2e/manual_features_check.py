"""The optional features on the six customer manuals through the agent worker (no browser):
tightening-order figures, part designations, vehicle memory, fleet statuses, inspection record, audit chain.

    PYTHONPATH=. .venv/bin/python tests/e2e/manual_features_check.py --data-dir DIR_WITH_6_PDF --mock-dir MOCK_DIR
With LLM_API_KEY set the answers are generated by the model (ALLOW_EXTERNAL_EVIDENCE=true), as on the stand.
"""
import argparse
import json
import os
import subprocess
import sys
from collections import Counter
from pathlib import Path
from tempfile import TemporaryDirectory
from unittest.mock import patch

from fastapi.testclient import TestClient

CHECKS = [  # engine, question, figure the manual names for this engine
    ('ЗМЗ-40905.10', 'В каком порядке затягивать болты крепления головки цилиндров?', '142'),
    ('ЗМЗ-5234.10', 'В каком порядке затягивать гайки головки цилиндров?', '86'),
    ('ЯМЗ-236М2', 'В каком порядке подтягивать гайки крепления головок цилиндров?', '6'),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir', type=Path, required=True)
    parser.add_argument('--mock-dir', type=Path, required=True)
    args = parser.parse_args()
    sys.path.insert(0, str(args.mock_dir.resolve(strict=True)))
    from mock_ml.app import app as mock_ml
    from mock_toir.app import app as mock_toir
    from mobile_smoke import serve

    external = bool(os.environ.get('LLM_API_KEY'))
    vehicles = json.loads((args.mock_dir / 'data' / 'vehicles.json').read_text(encoding='utf-8'))['vehicles']
    with TemporaryDirectory() as state, serve(mock_ml) as ml_url, serve(mock_toir) as toir_url, patch.dict(os.environ, {
        'DATA_DIR': str(args.data_dir), 'VEHICLES_PATH': str(args.mock_dir / 'data' / 'vehicles.json'),
        'ARTIFACTS_DIR': state, 'PLANNER_MODE': 'local', 'WEB_RETRIEVAL_MODE': 'team',
        'AGENT_ARCHITECTURE': 'a' if external else 'baseline', 'ALLOW_EXTERNAL_EVIDENCE': str(external).lower(),
        'ML_API_URL': ml_url, 'MAINTENANCE_API_URL': toir_url,
    }):
        subprocess.run([sys.executable, '-m', 'ml.manual_corpus'], check=True)
        from ml.worker import create_app
        with TestClient(create_app()) as client:
            def run(vehicle, **turn):
                session = max(vehicle['sessions'], key=lambda item: item['checked_at'])['session_id']
                response = client.post('/run', json={'turn': {
                    'vehicle_id': vehicle['vehicle_id'], 'session_id': session, 'actor_id': 'check', **turn}})
                assert response.status_code == 200, response.text
                return response.json()

            fleet = client.get('/fleet').json()['vehicles']
            states = Counter(vehicle['fleet_status']['state'] for vehicle in fleet)
            assert sorted(vehicle['fleet_status']['rank'] for vehicle in fleet) == list(range(1, len(fleet) + 1))
            print(f'PASS — статусы парка: {dict(states)}')

            for engine, question, figure in CHECKS:
                vehicle = next(item for item in vehicles if item['engine_model'] == engine)
                answer = run(vehicle, message=question)
                figures = [(item['figure'], item['pdf_page']) for item in answer['figures']]
                assert figures and figures[0][0] == figure, (engine, figures, answer['action'])
                assert any(note.startswith(f'Порядок затяжки показан на рисунке {figure}') for note in answer['limitations'])
                print(f'PASS — {engine}: порядок затяжки → рисунок {figure} (стр. {figures[0][1]}), без угадывания')

            pump = next(item for item in vehicles if item['engine_model'] == 'ЯМЗ-236М2')
            parts = run(pump, message='Какое обозначение детали у водяного насоса?')
            designations = [item['designation'] for item in parts['part_numbers']]
            assert designations or parts['part_numbers_note'] or not parts['claims'], parts
            print(f'PASS — обозначения деталей: {designations[:5] or parts["part_numbers_note"] or "нет утверждений"}')

            def repeats(vehicle):
                faults = Counter(s['anomaly_type'] for s in vehicle['sessions'] if s['status'] == 'anomaly')
                return bool(faults) and faults.most_common(1)[0][1] > 1

            repeat = next(item for item in vehicles if repeats(item))
            history = run(repeat, command='get_diagnostic_history')
            assert any(line.startswith('Повторялось:') for line in history['memory']), history['memory']
            print(f'PASS — память по машине {repeat["vehicle_id"]}: {history["memory"][1]}')

            diagnosis = run(repeat, command='diagnose')
            inspection = run(repeat, command='record_inspection', inspection={'outcome': 'confirmed', 'marks': 'matched'})
            assert inspection['diagnostic'] is None and len(inspection['inspections']) == 1
            again = run(repeat, command='diagnose')
            assert again['diagnostic'] == diagnosis['diagnostic']
            print('PASS — результат осмотра записан, диагноз не изменился')

            session = max(repeat['sessions'], key=lambda item: item['checked_at'])['session_id']
            chain = client.get('/audit', params={'vehicle_id': repeat['vehicle_id'], 'session_id': session}).json()['entries']
            assert [entry['command'] for entry in chain][-3:] == ['diagnose', 'record_inspection', 'diagnose']
            assert all(entry['actor_id'] == 'check' for entry in chain)
            print(f'PASS — журнал аудита: {len(chain)} записей по проверке {session}')
    print('Модель:', 'включена' if external else 'выключена (без LLM_API_KEY)')


if __name__ == '__main__':
    main()
